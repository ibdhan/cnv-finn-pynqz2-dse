#!/usr/bin/env python3
"""validate_npz.py -- top-1 accuracy of a FINN accelerator on a PYNQ board WITHOUT internet access.

Derived from the validate.py generated by FINN v0.10.1, with two changes:
  - the test set is read from a .npz file (x, y) produced on the host with dataset_loading
    (code/analysis/make_cifar10_npz.py; same format as the original validate.py), instead of being downloaded on the board;
  - total wall time is recorded and results are written to JSON.

Usage (on the board, inside the FINN deployment folder):
  sudo ./pynq_run.sh python3 validate_npz.py --npz cifar10_test.npz --batchsize 1000

Note: fps_incl_host includes Python overhead (packing/unpacking, buffer copies) and is NOT the pure
accelerator throughput. Accelerator throughput is measured with
`python3 driver.py --exec_mode=throughput_test --batchsize N`.
"""
import argparse
import json
import time
from datetime import datetime

import numpy as np
from driver import io_shape_dict
from driver_base import FINNExampleOverlay

p = argparse.ArgumentParser(description="Top-1 validation of a FINN accelerator from a .npz file")
p.add_argument("--npz", required=True, help=".npz file with arrays x (images) and y (labels)")
p.add_argument("--batchsize", type=int, default=1000)
p.add_argument("--bitfile", default="resizer.bit")
p.add_argument("--platform", default="zynq-iodma")
p.add_argument("--out", default="accuracy.json")
a = p.parse_args()

d = np.load(a.npz)
x, y = d["x"], d["y"]
total = x.shape[0]
bs = a.batchsize
assert total % bs == 0, f"number of samples {total} must be divisible by batchsize {bs}"
print(f"data: x{tuple(x.shape)} {x.dtype}, y{tuple(y.shape)} {y.dtype}")

driver = FINNExampleOverlay(
    bitfile_name=a.bitfile,
    platform=a.platform,
    io_shape_dict=io_shape_dict,
    batch_size=bs,
    runtime_weight_dir="runtime_weights/",
)

n_batches = total // bs
x = x.reshape(n_batches, bs, -1)
y = y.reshape(n_batches, bs)

ok = 0
t0 = time.perf_counter()
for i in range(n_batches):
    ibuf = x[i].reshape(driver.ibuf_packed_device[0].shape)
    driver.copy_input_data_to_device(ibuf)
    driver.execute_on_buffers()
    obuf = np.empty_like(driver.obuf_packed_device[0])
    driver.copy_output_data_from_device(obuf)
    ok += int((obuf.flatten() == y[i].flatten()).sum())
    print(f"batch {i + 1}/{n_batches}: {ok} correct of {(i + 1) * bs}")
wall = time.perf_counter() - t0

res = {
    "date": datetime.now().isoformat(timespec="seconds"),
    "npz": a.npz,
    "bitfile": a.bitfile,
    "n_samples": total,
    "batchsize": bs,
    "correct": ok,
    "top1_acc_pct": 100.0 * ok / total,
    "wall_s": wall,
    "fps_incl_host": total / wall,
}
print(json.dumps(res, indent=2))
with open(a.out, "w") as f:
    json.dump(res, f, indent=2)
print(f"Final accuracy: {res['top1_acc_pct']:.2f}%  -> {a.out}")
