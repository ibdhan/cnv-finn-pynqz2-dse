#!/usr/bin/env python3
"""make_cifar10_npz.py -- write the CIFAR-10 test set to a single .npz (x: N x 32 x 32 x 3 uint8, y: N int)
so that the board, which has no internet access, can validate accuracy with deploy/validate_npz.py.

Uses the same loader as the validate.py generated by FINN (package `dataset_loading`, available in the
FINN container). Run INSIDE the FINN container:
  cd $FINN_ROOT && ./run-docker.sh python <repo>/04_code/analysis/make_cifar10_npz.py --out $FINN_BUILD_DIR/cifar10_test.npz
(In our run this step was done in a notebook cell; this script reproduces it.)
"""
import argparse
import numpy as np
from dataset_loading import cifar

p = argparse.ArgumentParser()
p.add_argument("--out", required=True)
p.add_argument("--download-dir", default="/tmp")
a = p.parse_args()
trainx, trainy, testx, testy, valx, valy = cifar.load_cifar_data(a.download_dir, download=True, one_hot=False)
testx, testy = np.asarray(testx), np.asarray(testy)
assert testx.dtype == np.uint8 and testx.shape[1:] == (32, 32, 3), (testx.dtype, testx.shape)
np.savez(a.out, x=testx, y=testy.astype(np.int32))
print(f"x{testx.shape} {testx.dtype}, y{testy.shape} -> {a.out}")
